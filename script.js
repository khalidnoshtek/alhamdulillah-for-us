/* ════════════════════════════════════════════════════════════
   Procedural ambient — calm solo piano
   ════════════════════════════════════════════════════════════ */
class Ambient {
  constructor() {
    this.ctx = null; this.master = null; this.bus = null;
    this.timer = null; this.playing = false;
    this.mode = 'procedural';    // 'procedural' or 'kina'
    this.kinaAudio = null;
    this.volume = 0.32;          // 0..1
    this.scale   = [174.61, 220.00, 261.63, 329.63, 349.23, 392.00, 440.00, 523.25];
    this.weights = [3, 2, 3, 2, 1, 2, 1, 1];
  }
  async loadKina() {
    if (this.kinaAudio) return this.kinaAudio;
    return new Promise((resolve) => {
      const a = new Audio();
      a.loop = true;
      a.preload = 'auto';
      const done = (val) => { resolve(val); a.removeEventListener('canplaythrough', onOK); a.removeEventListener('error', onErr); };
      const onOK  = () => { this.kinaAudio = a; done(a); };
      const onErr = () => done(null);
      a.addEventListener('canplaythrough', onOK, { once: true });
      a.addEventListener('error',          onErr, { once: true });
      a.src = 'assets/audio/kina.mp3';
      setTimeout(() => { if (!this.kinaAudio) done(null); }, 4000);
    });
  }
  async setMode(mode) {
    if (mode === this.mode) return true;
    if (mode === 'kina') {
      const ok = await this.loadKina();
      if (!ok) return false;  // file missing — caller should snap UI back
    }
    const wasPlaying = this.playing;
    if (wasPlaying) this.stop();
    this.mode = mode;
    if (wasPlaying) setTimeout(() => this.start(), 120);
    return true;
  }
  fade(target, ms) {
    if (this.mode === 'kina' && this.kinaAudio) {
      const start = this.kinaAudio.volume, t0 = performance.now();
      const step = (t) => {
        const k = Math.min(1, (t - t0) / ms);
        this.kinaAudio.volume = start + (target - start) * k;
        if (k < 1) requestAnimationFrame(step);
      };
      requestAnimationFrame(step);
    } else if (this.master) {
      const now = this.ctx.currentTime;
      this.master.gain.cancelScheduledValues(now);
      this.master.gain.setValueAtTime(this.master.gain.value, now);
      this.master.gain.linearRampToValueAtTime(target, now + ms / 1000);
    }
  }
  setVolume(v) {
    this.volume = Math.max(0, Math.min(1, v));
    if (this.playing) this.fade(this.volume, 200);
  }
  init() {
    if (this.master) return;        // fully initialized
    if (!this.ctx) {
      const Ctx = window.AudioContext || window.webkitAudioContext;
      this.ctx = new Ctx();
    }
    this.master = this.ctx.createGain();
    this.master.gain.value = 0;
    this.master.connect(this.ctx.destination);

    // Soft limiter — prevents the harsh noise when 2-3 notes burst at once
    // and the reverb tail piles up past 0dB
    const limiter = this.ctx.createDynamicsCompressor();
    limiter.threshold.value = -10;
    limiter.knee.value = 6;
    limiter.ratio.value = 12;
    limiter.attack.value = 0.003;
    limiter.release.value = 0.15;
    limiter.connect(this.master);

    const reverb = this.ctx.createConvolver();
    reverb.buffer = this.makeIR(3.6, 2.2);
    const dry = this.ctx.createGain(); dry.gain.value = 0.5;
    const wet = this.ctx.createGain(); wet.gain.value = 0.6;
    dry.connect(limiter);
    wet.connect(reverb);
    reverb.connect(limiter);

    const lp = this.ctx.createBiquadFilter();
    lp.type = 'lowpass'; lp.frequency.value = 3800; lp.Q.value = 0.4;
    lp.connect(dry); lp.connect(wet);
    this.bus = lp;
  }
  makeIR(seconds, decay) {
    const sr = this.ctx.sampleRate;
    const len = Math.floor(sr * seconds);
    const ir = this.ctx.createBuffer(2, len, sr);
    for (let ch = 0; ch < 2; ch++) {
      const d = ir.getChannelData(ch);
      for (let i = 0; i < len; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / len, decay);
    }
    return ir;
  }
  pickNote() {
    const total = this.weights.reduce((a, b) => a + b, 0);
    let r = Math.random() * total;
    for (let i = 0; i < this.scale.length; i++) {
      r -= this.weights[i];
      if (r <= 0) return this.scale[i];
    }
    return this.scale[0];
  }
  playNote(time, freq) {
    const ctx = this.ctx;
    const dur = 5.5 + Math.random() * 3;
    const env = ctx.createGain();
    env.gain.setValueAtTime(0, time);
    env.gain.linearRampToValueAtTime(0.34, time + 0.04);
    env.gain.exponentialRampToValueAtTime(0.0001, time + dur);

    const o1 = ctx.createOscillator();
    o1.type = 'sine'; o1.frequency.value = freq;
    const g1 = ctx.createGain(); g1.gain.value = 1;
    o1.connect(g1); g1.connect(env);

    const o2 = ctx.createOscillator();
    o2.type = 'triangle'; o2.frequency.value = freq * 2; o2.detune.value = 4;
    const g2 = ctx.createGain(); g2.gain.value = 0.12;
    o2.connect(g2); g2.connect(env);

    const o3 = ctx.createOscillator();
    o3.type = 'sine'; o3.frequency.value = freq * 3;
    const g3 = ctx.createGain(); g3.gain.value = 0.04;
    const e3 = ctx.createGain();
    e3.gain.setValueAtTime(0, time);
    e3.gain.linearRampToValueAtTime(0.35, time + 0.02);
    e3.gain.exponentialRampToValueAtTime(0.0001, time + 1.0);
    o3.connect(g3); g3.connect(e3); e3.connect(env);

    if (ctx.createStereoPanner) {
      const pan = ctx.createStereoPanner();
      pan.pan.value = (Math.random() - 0.5) * 0.45;
      env.connect(pan); pan.connect(this.bus);
    } else {
      env.connect(this.bus);
    }
    o1.start(time); o2.start(time); o3.start(time);
    o1.stop(time + dur); o2.stop(time + dur); o3.stop(time + 1.2);
  }
  scheduleLoop() {
    if (!this.playing || !this.ctx) return;
    const now = this.ctx.currentTime;
    const gap = 1.7 + Math.random() * 2.6;
    const next = now + gap;
    if (Math.random() < 0.16) {
      this.playNote(next, this.pickNote());
      this.playNote(next + 0.04, this.pickNote());
      if (Math.random() < 0.35) this.playNote(next + 0.09, this.pickNote());
    } else {
      this.playNote(next, this.pickNote());
    }
    this.timer = setTimeout(() => this.scheduleLoop(), gap * 1000);
  }
  async start() {
    if (this.mode === 'kina') {
      const kina = await this.loadKina();
      if (kina) {
        try {
          kina.volume = 0;
          await kina.play();
          this.playing = true;
          this.fade(this.volume, 4000);
          return;
        } catch (e) { /* play() blocked */ return; }
      }
      // fall through to procedural if kina file missing
      this.mode = 'procedural';
    }
    this.init();
    if (this.ctx.state === 'suspended') await this.ctx.resume();
    const now = this.ctx.currentTime;
    this.master.gain.cancelScheduledValues(now);
    this.master.gain.setValueAtTime(this.master.gain.value, now);
    this.master.gain.linearRampToValueAtTime(this.volume, now + 4);
    if (!this.playing) {
      this.playing = true;
      this.playNote(now + 0.5, this.pickNote());
      this.timer = setTimeout(() => this.scheduleLoop(), 1800);
    }
  }
  stop() {
    if (this.mode === 'kina' && this.kinaAudio) {
      const start = this.kinaAudio.volume, t0 = performance.now(), dur = 2500;
      const step = (t) => {
        const k = Math.min(1, (t - t0) / dur);
        this.kinaAudio.volume = start * (1 - k);
        if (k < 1) requestAnimationFrame(step);
        else this.kinaAudio.pause();
      };
      requestAnimationFrame(step);
      this.playing = false;
      return;
    }
    if (!this.ctx) return;
    const now = this.ctx.currentTime;
    this.master.gain.cancelScheduledValues(now);
    this.master.gain.setValueAtTime(this.master.gain.value, now);
    this.master.gain.linearRampToValueAtTime(0, now + 2.5);
    this.playing = false;
    if (this.timer) { clearTimeout(this.timer); this.timer = null; }
  }
}
